(function(){
  let activePopover = null;

  function closePopover(){
    if(activePopover){ activePopover.remove(); activePopover = null; }
    document.removeEventListener('click', outsideHandler, true);
    window.removeEventListener('scroll', closePopover, true);
    window.removeEventListener('resize', closePopover);
  }
  function outsideHandler(e){
    if(activePopover && !activePopover.contains(e.target) && !e.target.classList.contains('gloss')){
      closePopover();
    }
  }
  function openPopover(term, anchorEl){
    closePopover();
    const entry = window.PBS_GLOSSARY[term];
    if(!entry) return;
    const pop = document.createElement('div');
    pop.className = 'gloss-popover';
    pop.innerHTML =
      `<div class="gp-term"><span>📖 ${term}</span><button class="gp-close" aria-label="닫기">✕</button></div>` +
      `<div>${entry.def}</div>` +
      (entry.kids ? `<div class="gp-kids"><b>🧒 쉬운 설명</b><br>${entry.kids}</div>` : '');
    document.body.appendChild(pop);

    const r = anchorEl.getBoundingClientRect();
    const popW = 300;
    let left = Math.min(Math.max(8, r.left), window.innerWidth - popW - 8);
    let top = r.bottom + 8;
    if(top + 160 > window.innerHeight){ top = Math.max(8, r.top - 168); }
    pop.style.left = left + 'px';
    pop.style.top = top + 'px';
    requestAnimationFrame(()=> pop.classList.add('show'));

    pop.querySelector('.gp-close').addEventListener('click', closePopover);
    activePopover = pop;
    setTimeout(()=>{
      document.addEventListener('click', outsideHandler, true);
      window.addEventListener('scroll', closePopover, true);
      window.addEventListener('resize', closePopover);
    }, 0);
  }

  function initGlossary(root){
    (root || document).querySelectorAll('.gloss[data-term]').forEach(el=>{
      if(el.dataset.glossBound) return;
      el.dataset.glossBound = '1';
      el.setAttribute('tabindex', '0');
      el.setAttribute('role', 'button');
      el.addEventListener('click', (e)=>{ e.stopPropagation(); openPopover(el.dataset.term, el); });
      el.addEventListener('keydown', (e)=>{
        if(e.key === 'Enter' || e.key === ' '){ e.preventDefault(); openPopover(el.dataset.term, el); }
      });
    });
  }

  function renderGlossaryList(container, terms){
    const list = terms || Object.keys(window.PBS_GLOSSARY);
    container.innerHTML = list.map(term=>{
      const e = window.PBS_GLOSSARY[term];
      if(!e) return '';
      return `<div class="gloss-list-item">
        <div class="gl-term">📖 ${term}</div>
        <div class="gl-def">${e.def}</div>
        ${e.kids ? `<div class="gl-kids">🧒 ${e.kids}</div>` : ''}
      </div>`;
    }).join('');
  }

  window.PBS_initGlossary = initGlossary;
  window.PBS_renderGlossaryList = renderGlossaryList;
  window.PBS_closeGlossaryPopover = closePopover;

  document.addEventListener('DOMContentLoaded', ()=> initGlossary(document));
})();
